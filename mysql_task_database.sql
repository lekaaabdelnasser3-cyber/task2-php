CREATE DATABASE IF NOT EXISTS `mysql_task`
  DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `mysql_task`;

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS `orders`;
DROP TABLE IF EXISTS `products`;
DROP TABLE IF EXISTS `employees`;
DROP TABLE IF EXISTS `customers`;

SET FOREIGN_KEY_CHECKS = 1;

-- ----------------------------------------------------------------------------
-- customers  (task 1, 2, 3, 6, 7, 9, 10, 11)
-- `password` holds a bcrypt hash written by PHP password_hash() (task 11)
-- ----------------------------------------------------------------------------
CREATE TABLE `customers` (
  `id`       INT           NOT NULL AUTO_INCREMENT,
  `name`     VARCHAR(100)  NOT NULL,
  `email`    VARCHAR(100)  NOT NULL,
  `password` VARCHAR(255)  NOT NULL,
  `salary`   DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  `city`     VARCHAR(50)   NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_customers_email` (`email`),
  KEY `idx_customers_name` (`name`),
  KEY `idx_customers_salary` (`salary`),
  KEY `idx_customers_city_salary` (`city`, `salary`),
  CONSTRAINT `chk_customers_salary` CHECK (`salary` >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- products  (task 4, 8, 10)
-- ----------------------------------------------------------------------------
CREATE TABLE `products` (
  `id`    INT           NOT NULL AUTO_INCREMENT,
  `name`  VARCHAR(100)  NOT NULL,
  `price` DECIMAL(10,2) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_products_name` (`name`),
  CONSTRAINT `chk_products_price` CHECK (`price` > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- orders: one row = one product bought by one customer in some quantity
-- (task 3, 4, 8, 10)
-- ----------------------------------------------------------------------------
CREATE TABLE `orders` (
  `id`          INT NOT NULL AUTO_INCREMENT,
  `customer_id` INT NOT NULL,
  `product_id`  INT NOT NULL,
  `quantity`    INT NOT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_orders_customer` (`customer_id`),
  KEY `idx_orders_product` (`product_id`),
  CONSTRAINT `fk_orders_customer` FOREIGN KEY (`customer_id`) REFERENCES `customers` (`id`)
    ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `fk_orders_product` FOREIGN KEY (`product_id`) REFERENCES `products` (`id`)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `chk_orders_quantity` CHECK (`quantity` > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- employees: manager_id points back to employees.id (self-join, task 5)
-- ----------------------------------------------------------------------------
CREATE TABLE `employees` (
  `id`         INT          NOT NULL AUTO_INCREMENT,
  `name`       VARCHAR(100) NOT NULL,
  `manager_id` INT          NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_employees_manager` (`manager_id`),
  CONSTRAINT `fk_employees_manager` FOREIGN KEY (`manager_id`) REFERENCES `employees` (`id`)
    ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

